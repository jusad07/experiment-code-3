import numpy as np
import matplotlib.pyplot as plt

C = 420
R = 1.0
N = np.array([3, 4, 7, 9, 12])

reuse_ratio = np.sqrt(3 * N)
D = R * reuse_ratio
channels_per_cell = C / N

print(f"{'N':<10}{'D/R':<15}{'D (km)':<15}{'Channels/Cell':<15}")

for n, ratio, distance, channels in zip(N, reuse_ratio, D, channels_per_cell):
    print(f"{n:<10}{ratio:<15.2f}{distance:<15.2f}{channels:<15.2f}")

plt.figure(figsize=(8, 5))
plt.plot(N, D, 'o-', linewidth=2, markersize=8)
plt.xlabel("Cluster Size (N)")
plt.ylabel("Reuse Distance D (km)")
plt.title("Reuse Distance vs Cluster Size")
plt.grid(True)
plt.xticks(N)
plt.show()

plt.figure(figsize=(8, 5))
plt.plot(N, channels_per_cell, 's-', linewidth=2, markersize=8)
plt.xlabel("Cluster Size (N)")
plt.ylabel("Channels Per Cell")
plt.title("Channels Per Cell vs Cluster Size")
plt.grid(True)
plt.xticks(N)
plt.show()

required_distance = 4.0
feasible_N = N[D >= required_distance]

if len(feasible_N) > 0:
    selected_N = feasible_N[0]
    selected_D = D[N == selected_N][0]
    selected_channels = C / selected_N

    print("Selected Cluster Size:", selected_N)
    print("Reuse Distance:", round(selected_D, 2), "km")
    print("Channels Per Cell:", round(selected_channels, 2))